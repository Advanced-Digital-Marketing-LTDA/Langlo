<h1>Privacy in this foundation</h1>
<p>
  Langlo handles your account email and authentication and session data to let
  you sign in and keep your account session active. It stores learning answers,
  progress and review history, as well as content you save in Library.
</p>
<p>
  AI analysis may send the text you select and related prompt context to OpenAI.
  The selected text may also be sent to TypeSafe Jev for prompt-injection
  screening.
</p>
<p>
  A complete retention and backup-deletion schedule has not been published or
  verified. While this remains unresolved, do not submit sensitive or
  confidential content.
</p>
<p>
  Operational diagnostics contain a random request reference and a safe error
  category. Submitted answers, tokens, cookies and exception messages are
  excluded from those diagnostics.
</p>
